-- =============================================================================
-- 0017: orphaned private-file cleanup (Q-07-15 follow-up; T8, P16, T9)
--
-- STATUS (3 November 2026): PREPARED ONLY. Not applied to any hosted database. The matching
-- Edge Function (supabase/functions/storage-cleanup) is not deployed and not scheduled. Both
-- need the owner's explicit authorization. Tested in the simulated PostgreSQL sandbox:
-- supabase/tests/database/085_storage_cleanup.test.sql.
--
-- Why: deleting a file record, replacing a video or thumbnail, or deleting a lesson or module
-- removes the database reference but not the Storage object (0010, Q-07-15). Those objects are
-- unreachable through the app (media_access only signs referenced paths), but they still hold
-- course material and cost storage.
--
-- What this adds (no table, policy or function that existed before is changed):
--   private.storage_cleanup_audit           append-only record of every cleanup run and decision
--   private.storage_object_orphaned(...)     the single eligibility rule (below)
--   public.storage_cleanup_candidates(...)   lists eligible objects; writes nothing
--   public.storage_cleanup_check(...)        re-checks ONE object immediately before deletion,
--                                            and audits the decision
--   public.storage_cleanup_result(...)       audits what the Storage API deletion did
--   public.storage_cleanup_run_event(...)    audits the start and end of a run
-- The public functions are callable by service_role ONLY (the Edge Function's secret key).
-- anon and authenticated cannot execute them, and nothing here deletes an object: deletion is
-- done by the Edge Function through the Storage API, which removes the stored file itself.
--
-- Eligibility (all must hold):
--   1. The object is in course-files, course-video or course-thumbnails, and its first path
--      segment is a UUID (an AQS course path). Anything else is never touched.
--   2. It is older than the grace period: at least 24 hours, whatever the caller asks
--      (default 7 days). Uploads in progress and just-replaced files are therefore never
--      candidates.
--   3. No record references it:
--        course-files       lesson_resources.storage_path = name
--                           courses.thumbnail_path = 'course-files/' || name
--        course-video       lesson_contents.video_path = name
--        course-thumbnails  courses.thumbnail_path = 'course-thumbnails/' || name
--      These are the only columns that hold Storage paths (0007, 0010). Clones (0009a) never
--      share paths: every path starts with its own course ID.
-- Paths are generated by the course functions with random UUIDs, so an unreferenced object
-- cannot become referenced again; the re-check right before deletion closes the remaining gap.
-- =============================================================================

-- 1. Append-only audit -------------------------------------------------------------------------
create table private.storage_cleanup_audit (
  id              bigint generated always as identity primary key,
  occurred_at     timestamptz not null default now(),
  run_id          uuid not null,
  action          text not null check (action in (
                    'run_started', 'run_finished',
                    'dry_run_candidate', 'delete_approved', 'skipped',
                    'deleted', 'delete_failed')),
  dry_run         boolean not null,
  bucket_id       text,
  object_name     text,
  object_created_at timestamptz,
  detail          jsonb not null default '{}'::jsonb,
  db_session_user text not null default session_user
);
comment on table private.storage_cleanup_audit is
  'Append-only history of orphaned-file cleanup runs (0017). Not reachable by any client role.';
create index storage_cleanup_audit_run on private.storage_cleanup_audit (run_id, bucket_id, object_name);

create trigger storage_cleanup_audit_no_update   before update   on private.storage_cleanup_audit for each row       execute function private.forbid_change();
create trigger storage_cleanup_audit_no_delete   before delete   on private.storage_cleanup_audit for each row       execute function private.forbid_change();
create trigger storage_cleanup_audit_no_truncate before truncate on private.storage_cleanup_audit for each statement execute function private.forbid_change();

revoke all on table private.storage_cleanup_audit from public, anon, authenticated, service_role;

-- 2. The eligibility rule ------------------------------------------------------------------------
create function private.storage_object_orphaned(p_bucket text, p_name text, p_created_at timestamptz, p_min_age_hours integer)
returns boolean
language sql
stable
set search_path = ''
as $$
  select p_bucket in ('course-files', 'course-video', 'course-thumbnails')
     and private.object_course(p_name) is not null
     and p_created_at is not null
     and p_created_at < now() - make_interval(hours => greatest(coalesce(p_min_age_hours, 168), 24))
     and not exists (select 1 from public.lesson_resources r where p_bucket = 'course-files' and r.storage_path = p_name)
     and not exists (select 1 from public.lesson_contents b where p_bucket = 'course-video' and b.video_path = p_name)
     and not exists (select 1 from public.courses c where c.thumbnail_path = p_bucket || '/' || p_name);
$$;

create function private.storage_cleanup_require_run(p_run uuid)
returns void
language plpgsql
stable
set search_path = ''
as $$
begin
  if p_run is null or not exists (select 1 from private.storage_cleanup_audit a
                                   where a.run_id = p_run and a.action = 'run_started') then
    raise exception 'AQS: unknown cleanup run' using errcode = '22023';
  end if;
  if exists (select 1 from private.storage_cleanup_audit a where a.run_id = p_run and a.action = 'run_finished') then
    raise exception 'AQS: this cleanup run has finished' using errcode = '22023';
  end if;
end;
$$;

revoke execute on function private.storage_object_orphaned(text, text, timestamptz, integer),
  private.storage_cleanup_require_run(uuid)
  from public, anon, authenticated, service_role;

-- 3. Run start and end ---------------------------------------------------------------------------
create function public.storage_cleanup_run_event(p_run uuid, p_event text, p_dry_run boolean, p_detail jsonb default '{}'::jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_run is null or p_dry_run is null then
    raise exception 'AQS: a run ID and the dry-run flag are required' using errcode = '22023';
  end if;
  if p_event = 'run_started' then
    if exists (select 1 from private.storage_cleanup_audit a where a.run_id = p_run) then
      raise exception 'AQS: this cleanup run already exists' using errcode = '22023';
    end if;
  elsif p_event = 'run_finished' then
    perform private.storage_cleanup_require_run(p_run);
  else
    raise exception 'AQS: unknown cleanup event' using errcode = '22023';
  end if;
  insert into private.storage_cleanup_audit (run_id, action, dry_run, detail)
  values (p_run, p_event, p_dry_run, coalesce(p_detail, '{}'::jsonb));
end;
$$;

-- 4. Candidates (read only) ----------------------------------------------------------------------
create function public.storage_cleanup_candidates(p_min_age_hours integer default 168, p_limit integer default 100)
returns table (bucket_id text, object_name text, created_at timestamptz)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_limit is null or p_limit not between 1 and 1000 then
    raise exception 'AQS: the limit must be between 1 and 1000' using errcode = '22023';
  end if;
  return query
    select o.bucket_id, o.name, o.created_at
      from storage.objects o
     where o.bucket_id in ('course-files', 'course-video', 'course-thumbnails')
       and private.storage_object_orphaned(o.bucket_id, o.name, o.created_at, p_min_age_hours)
     order by o.created_at, o.bucket_id, o.name
     limit p_limit;
end;
$$;

-- 5. Re-check one object immediately before deletion ----------------------------------------------
-- Locks the object's row, re-applies the rule and records the decision. Returns true only when
-- the object may be deleted now. In a dry run it records 'dry_run_candidate' and returns false.
-- The lock only serialises concurrent checks of the same object and ends with this call; the
-- Edge Function deletes straight after it returns true.
create function public.storage_cleanup_check(p_run uuid, p_bucket text, p_name text, p_min_age_hours integer, p_dry_run boolean)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_created timestamptz;
  v_ok      boolean;
begin
  perform private.storage_cleanup_require_run(p_run);
  if p_dry_run is null then
    raise exception 'AQS: the dry-run flag is required' using errcode = '22023';
  end if;
  select o.created_at into v_created
    from storage.objects o
   where o.bucket_id = p_bucket and o.name = p_name
     for update;
  if not found then
    insert into private.storage_cleanup_audit (run_id, action, dry_run, bucket_id, object_name, detail)
    values (p_run, 'skipped', p_dry_run, p_bucket, p_name, '{"reason": "object no longer exists"}');
    return false;
  end if;
  v_ok := private.storage_object_orphaned(p_bucket, p_name, v_created, p_min_age_hours);
  insert into private.storage_cleanup_audit (run_id, action, dry_run, bucket_id, object_name, object_created_at, detail)
  values (p_run,
          case when not v_ok then 'skipped' when p_dry_run then 'dry_run_candidate' else 'delete_approved' end,
          p_dry_run, p_bucket, p_name, v_created,
          case when v_ok then '{}'::jsonb else '{"reason": "referenced, too new or not an AQS course path"}'::jsonb end);
  return v_ok and not p_dry_run;
end;
$$;

-- 6. What the deletion did --------------------------------------------------------------------------
-- Accepted only for an object this run approved and has not yet reported on.
create function public.storage_cleanup_result(p_run uuid, p_bucket text, p_name text, p_deleted boolean, p_error text default null)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.storage_cleanup_require_run(p_run);
  if p_deleted is null then
    raise exception 'AQS: the outcome is required' using errcode = '22023';
  end if;
  if not exists (select 1 from private.storage_cleanup_audit a
                  where a.run_id = p_run and a.action = 'delete_approved'
                    and a.bucket_id = p_bucket and a.object_name = p_name)
     or exists (select 1 from private.storage_cleanup_audit a
                 where a.run_id = p_run and a.action in ('deleted', 'delete_failed')
                   and a.bucket_id = p_bucket and a.object_name = p_name) then
    raise exception 'AQS: this object was not approved for deletion in this run' using errcode = '22023';
  end if;
  insert into private.storage_cleanup_audit (run_id, action, dry_run, bucket_id, object_name, detail)
  values (p_run, case when p_deleted then 'deleted' else 'delete_failed' end, false, p_bucket, p_name,
          case when p_deleted then '{}'::jsonb else jsonb_build_object('error', left(coalesce(p_error, 'unknown'), 300)) end);
end;
$$;

-- 7. Execute privileges: service_role only --------------------------------------------------------
revoke execute on function
  public.storage_cleanup_run_event(uuid, text, boolean, jsonb),
  public.storage_cleanup_candidates(integer, integer),
  public.storage_cleanup_check(uuid, text, text, integer, boolean),
  public.storage_cleanup_result(uuid, text, text, boolean, text)
  from public, anon, authenticated;
grant execute on function
  public.storage_cleanup_run_event(uuid, text, boolean, jsonb),
  public.storage_cleanup_candidates(integer, integer),
  public.storage_cleanup_check(uuid, text, text, integer, boolean),
  public.storage_cleanup_result(uuid, text, text, boolean, text)
  to service_role;

comment on function public.storage_cleanup_candidates(integer, integer) is
  '0017: unreferenced AQS course objects older than the grace period (min 24 h). service_role only. Writes nothing.';
comment on function public.storage_cleanup_check(uuid, text, text, integer, boolean) is
  '0017: re-checks one object under a row lock right before deletion and audits the decision. service_role only.';
